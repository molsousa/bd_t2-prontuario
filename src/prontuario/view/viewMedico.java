    private void readTableMedico() throws SQLException {
        DefaultTableModel dftTableModel = (DefaultTableModel) jTableMedico.getModel();
        dftTableModel.setNumRows(0);
        
        MedicoDAO medDAO = new MedicoDAO();
        
        for(Medico medico : medDAO.listarMedicos()){
            dftTableModel.addRow(new Object[]{
                medico.getNroMedico(),
                medico.getNomeMedico(),
                medico.getCrm()
            });
            
        }
    }

