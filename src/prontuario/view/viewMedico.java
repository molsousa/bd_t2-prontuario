    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
        int nroMedico = (Integer.valueOf(nroMedicoField.getText()).intValue());
        EmailMedicoDAO emMedDAO = new EmailMedicoDAO();
        List<String> emails = new ArrayList<>();
        
        try{
            
            for(EmailMedico email : emMedDAO.buscarEmails(nroMedico)){
                emails.add(email.getEnderecoEmail());
            }
            
            jList1.setListData(emails.toArray(new String[0]));
            
        } catch (SQLException ex) {
            logger.log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

